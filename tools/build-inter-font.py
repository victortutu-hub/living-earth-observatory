"""LOT 30: Inter served locally instead of Google Fonts (index, Living Himalaya, Living Protein).

Input:  tmp/lot30/raw/inter/Inter-4.1.zip - the official release of rsms/inter
        (https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip), pinned by SHA-256;
        web/InterVariable.woff2 (Version 4.001; axes opsz 14-32, wght 100-900) and LICENSE.txt (SIL OFL 1.1).
Output: assets/fonts/inter-4.1-var-<hash10>.woff2  - the variable font limited to wght 200-600 (the weights
                                                     the pages requested from Google Fonts: 200,300,400,500,600),
                                                     opsz kept, every OpenType feature kept (tabular-nums is used),
                                                     subset to the Google Fonts latin + latin-ext + greek ranges
                                                     (the same characters Inter covered before; anything else
                                                     falls back to the system font as before);
        assets/fonts/OFL.txt                       - the licence, unchanged from the release;
        styles/inter.css                           - one @font-face per weight (200-600, normal, font-display swap),
                                                     unicode-range = the subset, so the weight matching stays the
                                                     same as with the Google stylesheet (e.g. 250 -> 200, 700 -> 600).
Deterministic: no timestamp is recalculated (recalcTimestamp=False), fixed options.
Usage: python -I tools/build-inter-font.py   (no network)
"""
import hashlib
import io
import os
import re
import zipfile

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SOURCE = os.path.join(ROOT, 'tmp/lot30/raw/inter/Inter-4.1.zip')
SOURCE_URL = 'https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip'
SOURCE_SHA256 = '9883fdd4a49d4fb66bd8177ba6625ef9a64aa45899767dde3d36aa425756b11e'
SOURCE_BYTES = 33707794
WEIGHTS = (200, 300, 400, 500, 600)
# Google Fonts unicode ranges of the latin, latin-ext and greek subsets of Inter.
RANGES = {
    'latin': 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
    'latin-ext': 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
    'greek': 'U+0370-0377, U+037A-037F, U+0384-038A, U+038C, U+038E-03A1, U+03A3-03FF',
}


def codepoints(ranges):
    out = set()
    for part in ', '.join(ranges).split(','):
        part = part.strip()[2:]
        a, _, b = part.partition('-')
        out.update(range(int(a, 16), int(b or a, 16) + 1))
    return sorted(out)


data = open(SOURCE, 'rb').read()
if len(data) != SOURCE_BYTES or hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
    raise SystemExit('Inter-4.1.zip: size or SHA-256 differs from the approved input')
z = zipfile.ZipFile(io.BytesIO(data))
licence = z.read('LICENSE.txt')
font = TTFont(io.BytesIO(z.read('web/InterVariable.woff2')), recalcTimestamp=False)
version = font['name'].getDebugName(5)
options = subset.Options()
options.layout_features = ['*']
options.name_IDs = ['*']
options.name_languages = ['*']
options.notdef_outline = True
options.flavor = 'woff2'
sub = subset.Subsetter(options=options)
sub.populate(unicodes=codepoints(RANGES.values()))
sub.subset(font)
# Then limit the weight axis (subsetting first: the instancer output keeps a lazily loaded gvar).
font = instancer.instantiateVariableFont(font, {'wght': (min(WEIGHTS), max(WEIGHTS))})
buf = io.BytesIO()
font.flavor = 'woff2'
font.save(buf)
woff2 = buf.getvalue()
digest = hashlib.sha256(woff2).hexdigest()
name = f'inter-4.1-var-{digest[:10]}.woff2'
fonts_dir = os.path.join(ROOT, 'assets/fonts')
os.makedirs(fonts_dir, exist_ok=True)
for old in os.listdir(fonts_dir):
    if re.fullmatch(r'inter-4\.1-var-[0-9a-f]{10}\.woff2', old) and old != name:
        os.remove(os.path.join(fonts_dir, old))
open(os.path.join(fonts_dir, name), 'wb').write(woff2)
open(os.path.join(fonts_dir, 'OFL.txt'), 'wb').write(licence)

unicode_range = ', '.join(RANGES.values())
faces = '\n'.join(
    "@font-face { font-family: 'Inter'; font-style: normal; font-weight: %d; font-display: swap; "
    "src: url('../assets/fonts/%s') format('woff2'); unicode-range: %s; }" % (w, name, unicode_range)
    for w in WEIGHTS)
css = f"""/* GENERATED by tools/build-inter-font.py - do not edit by hand.
   LOT 30: Inter {version} (rsms/inter v4.1, SIL Open Font License 1.1, assets/fonts/OFL.txt), served
   locally instead of Google Fonts. One variable file (wght 200-600, opsz), the same weights and
   unicode ranges (latin, latin-ext, greek) the pages requested before. sha256 {digest} */
{faces}
"""
open(os.path.join(ROOT, 'styles/inter.css'), 'w', encoding='utf-8', newline='\n').write(css)
print({'file': f'assets/fonts/{name}', 'bytes': len(woff2), 'sha256': digest, 'version': version,
       'ofl_sha256': hashlib.sha256(licence).hexdigest(), 'ofl_bytes': len(licence),
       'glyphs': len(font.getGlyphOrder()), 'axes': [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in font['fvar'].axes]})
