// LOT 30: Moon colour map from the NASA SVS CGI Moon Kit (https://svs.gsfc.nasa.gov/4720,
// "Please give credit for this item to: NASA's Scientific Visualization Studio").
// Input: lroc_color_poles_4k.tif (LROC WAC Hapke-normalised mosaic, 643/566/415 nm as R/G/B, polar
// gaps filled with LOLA albedo; "optimized for aesthetics, not science"), 4096x2048, 8-bit RGB,
// equirectangular, centred on 0 deg longitude, north up.
// Output: assets/moon/moon-lroc-color-4k-<hash10>.jpg (same pixels re-encoded as baseline JPEG,
// 4:4:4; no resampling, no contrast or colour change) + src/config/moon-color.js.
// Usage: node tools/build-moon-color.mjs   (reads tmp/lot30/raw/svs/lroc_color_poles_4k.tif; no network)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { fromArrayBuffer } from 'geotiff';
import { encodeJpeg } from './lib/jpeg-encode.mjs';

const ROOT = path.resolve(fileURLToPath(new URL('../', import.meta.url)));
const SOURCE = path.join(ROOT, 'tmp/lot30/raw/svs/lroc_color_poles_4k.tif');
const SOURCE_URL = 'https://svs.gsfc.nasa.gov/vis/a000000/a004700/a004720/lroc_color_poles_4k.tif';
const SOURCE_SHA256 = '918649a7f8ed2f1329b2cd95bb0d25483befdcb60ae1a66db681a637cc21344f';
const SOURCE_BYTES = 13095388;
const ASSET_DIR = path.join(ROOT, 'assets/moon');
const CONFIG_OUT = path.join(ROOT, 'src/config/moon-color.js');
export const QUALITY = 90;

const sha256 = (b) => crypto.createHash('sha256').update(b).digest('hex');
const input = fs.readFileSync(SOURCE);
if (input.length !== SOURCE_BYTES || sha256(input) !== SOURCE_SHA256) throw new Error('lroc_color_poles_4k.tif: size or SHA-256 differs from the approved input');
const tiff = await fromArrayBuffer(input.buffer.slice(input.byteOffset, input.byteOffset + input.length));
const image = await tiff.getImage(0);
const width = image.getWidth(); const height = image.getHeight();
if (width !== 4096 || height !== 2048 || image.getSamplesPerPixel() !== 3) throw new Error(`unexpected raster ${width}x${height}x${image.getSamplesPerPixel()}`);
const rgb = await image.readRasters({ interleave: true });
if (!(rgb instanceof Uint8Array)) throw new Error('expected 8-bit samples');

const jpeg = encodeJpeg({ width, height, data: rgb, channels: 3, quality: QUALITY });
const hash = sha256(jpeg);
const fileName = `moon-lroc-color-4k-${hash.slice(0, 10)}.jpg`;
fs.mkdirSync(ASSET_DIR, { recursive: true });
for (const old of fs.readdirSync(ASSET_DIR)) if (/^moon-lroc-color-4k-[0-9a-f]{10}\.jpg$/.test(old) && old !== fileName) fs.unlinkSync(path.join(ASSET_DIR, old));
fs.writeFileSync(path.join(ASSET_DIR, fileName), jpeg);

const asset = {
  file: `assets/moon/${fileName}`, sha256: hash, bytes: jpeg.length, width, height, format: `JPEG baseline 4:4:4, quality ${QUALITY} (tools/lib/jpeg-encode.mjs)`,
  representation: 'observed', adjustments: 'none (re-encoded only)',
  source: { name: 'NASA SVS CGI Moon Kit (ID 4720), LROC WAC Hapke normalized mosaic, 2019 colour version', url: SOURCE_URL, page: 'https://svs.gsfc.nasa.gov/4720', sha256: SOURCE_SHA256, bytes: SOURCE_BYTES, credit: "NASA's Scientific Visualization Studio", note: 'Optimized for aesthetics, not science (SVS); polar gaps filled with LOLA albedo (LDAM)' },
};
fs.writeFileSync(CONFIG_OUT, `// GENERATED by tools/build-moon-color.mjs - do not edit by hand.
// LOT 30: Moon colour map, NASA SVS CGI Moon Kit (credit: NASA's Scientific Visualization Studio).
export const MOON_COLOR_ASSET = Object.freeze(${JSON.stringify(asset)});
`);
console.log(JSON.stringify({ file: asset.file, bytes: asset.bytes, sha256: hash }));
