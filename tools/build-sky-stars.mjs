// LOT 15: point stars for the real sky, from the HYG database v4.4
// (astronexus, CC BY-SA 4.0; https://codeberg.org/astronexus/hyg). Keeps the
// stars with a Hipparcos id and V <= MAG_LIMIT (the NASA SVS Milky Way
// background omits all Hipparcos and Tycho stars, so no star is drawn twice).
// Positions: J2000 (HYG README: "for epoch and equinox 2000.0").
// Output: assets/sky/hyg-v44-stars-<hash>.bin (Float32 little-endian records
// [ra rad, dec rad, V, B-V or NaN], brightest first) + src/config/sky-stars.js.
// Usage: node tools/build-sky-stars.mjs   (reads tmp/sky/hyg_v44.csv.gz; no network)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { readHygHipparcos } from './lib/hyg-catalog.mjs';

const ROOT = path.resolve(fileURLToPath(new URL('../', import.meta.url)));
const SOURCE = path.join(ROOT, 'tmp/sky/hyg_v44.csv.gz');
const SOURCE_SHA256 = '00b349893b9a53106dd488d8371e8d2fa586043e500bb3cdb8bff3931682197d';
const ASSET_DIR = path.join(ROOT, 'assets/sky');
const CONFIG_OUT = path.join(ROOT, 'src/config/sky-stars.js');
export const MAG_LIMIT = 6.5;

const gz = fs.readFileSync(SOURCE);
const sha = crypto.createHash('sha256').update(gz).digest('hex');
if (sha !== SOURCE_SHA256) throw new Error(`HYG v4.4 checksum mismatch: ${sha}`);
const { rows, stars } = readHygHipparcos(gz);
const selected = stars.filter((s) => s.mag <= MAG_LIMIT).sort((a, b) => a.mag - b.mag || a.hip - b.hip);
const data = new Float32Array(selected.length * 4);
selected.forEach((s, i) => {
  data[i * 4] = (s.raDeg * Math.PI) / 180;
  data[i * 4 + 1] = (s.decDeg * Math.PI) / 180;
  data[i * 4 + 2] = s.mag;
  data[i * 4 + 3] = s.bv === null ? NaN : s.bv;
});
const bytes = Buffer.from(data.buffer);
const hash = crypto.createHash('sha256').update(bytes).digest('hex');
fs.mkdirSync(ASSET_DIR, { recursive: true });
const fileName = `hyg-v44-stars-${hash.slice(0, 10)}.bin`;
for (const old of fs.readdirSync(ASSET_DIR)) if (/^hyg-v44-stars-[0-9a-f]{10}\.bin$/.test(old) && old !== fileName) fs.unlinkSync(path.join(ASSET_DIR, old));
fs.writeFileSync(path.join(ASSET_DIR, fileName), bytes);

const meta = {
  file: `assets/sky/${fileName}`, sha256: hash, bytes: bytes.length,
  count: selected.length, magLimit: MAG_LIMIT, missingBv: selected.filter((s) => s.bv === null).length,
  brightest: selected[0].mag, faintest: selected.at(-1).mag,
  record: 'Float32LE [ra (rad), dec (rad), V (mag), B-V (mag, NaN if unknown)]', frame: 'ICRS / J2000 (epoch and equinox 2000.0)',
  source: { name: 'HYG database v4.4', url: 'https://codeberg.org/astronexus/hyg', file: 'data/hyg/CURRENT/hyg_v44.csv.gz', sha256: SOURCE_SHA256, rows, hipparcosRows: stars.length, license: 'CC BY-SA 4.0' },
};
fs.writeFileSync(CONFIG_OUT, `// GENERATED by tools/build-sky-stars.mjs - do not edit by hand.
// LOT 15: point stars of the real sky (HYG v4.4, Hipparcos stars with V <= ${MAG_LIMIT}).
// The derived file is published under CC BY-SA 4.0 (see NOTICE.md), separately from the repository licence.
export const SKY_STARS_ASSET = Object.freeze(${JSON.stringify(meta)});
`);
console.log(JSON.stringify(meta, null, 1));
